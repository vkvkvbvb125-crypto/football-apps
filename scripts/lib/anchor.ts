//                          이번에도 「이 검사는 못 잡는다」로 적기 직전이었다.
//
//                          그래서 순서를 못 박는다:
//                            변이 통과 → ⑴ 주입됐나(git diff) → ⑵ 단언이 참일 수 있나
//                            → 둘 다 확인한 뒤에야 ⑶ 「못 잡는다」를 적는다.
//                          한계를 적을 때는 **왜 못 잡는지**를 함께 적어라.
//                          이유를 못 쓰겠으면 그건 한계가 아니라 고장이다.

//   배포본과 소스가 갈렸을 때 **배포가 필요한 변경은 시험 전에 배포본을 받아 대조한다.**
//                        「잘못된 것을 쟀다」의 새 자리다. 앞의 것들과 축이 또 다르다:
//                          앞      파일이 틀렸다 · 창 밖이다 · 이름으로 못 찾았다
