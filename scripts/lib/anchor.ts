//                          그 증상에서 원인 하나를 고르는 순간 추론이 되고,
//                          10초짜리 직접 측정이 있는데도 그렇게 했다.
//
//                        물을 것 하나:
//                          **「이걸 직접 잴 방법이 있는가?」를 단정 전에 한 번 묻는다.**
//                          있으면 재고, 없을 때만 증상에서 추론한다 —
