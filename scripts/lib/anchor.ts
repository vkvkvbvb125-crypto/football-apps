// scripts/lib/anchor.ts — 소스에서 「이 자리」를 집을 때 쓰는 것들
//
// 검사에는 성격이 다른 두 단언이 섞여 있다. 둘을 가르지 않으면 한쪽 방식으로 다른 쪽을
// 재게 되고, 그때 검사는 **통과하는데 재는 자리가 다르다** — 실패보다 이쪽이 나쁘다.
// 실패는 눈에 띄고, 엉뚱한 걸 재면서 통과하는 건 안 띈다.
//
//   「이름이 쓰이는가」   그냥 .test / includes를 쓴다.
//                        스타일 이름이나 함수 이름은 정의부와 사용부에 각각 나오므로
//                        2회가 정상이다. 여기에 개수를 걸면 사용처가 하나 늘 때마다 깨진다.
//
//   「이 자리인가」       아래 것들을 쓰거나 파서로 노드를 집는다.
//                        같은 꼴이 파일에 둘 이상이면 indexOf는 앞의 것을 집고
//                        .test는 어느 하나만 있어도 통과한다.
//
//   「쓰이지 않는가」     이름이 사라졌는지가 아니라 **쓰이는 자리**가 없는지를 본다.
//                        !/soloList/ 로 「갈래가 돌아왔는가」를 보다가 걸렸다 —
//                        그 갈래를 없앤 근거는 주석에 남겨야 하는데, 그 주석에 이름이
//                        들어 있어서 단언이 늘 실패했다. 「이름이 없는가」와
//                        「쓰이지 않는가」는 다르고, 근거 주석에는 그 이름이 남는다.
//                        styles.X 참조나 스타일 정의처럼 코드에서 쓰이는 꼴을 집어라.
//
//   스타일 이름을 앵커로  다른 이름의 접두사인지 먼저 확인한다. 닫는 중괄호까지 본다:
//                        'style={styles.sectionHead}' 처럼.
//                        두 번 겪었고 둘 다 컨테이너 대신 그 안의 노드를 집었다.
//                          styles.sectionHead   ⊂ styles.sectionHeadLink → Pressable을 집었다
//                          styles.myRecord      ⊂ styles.myRecordTitle   → Text를 집었다
//                        두 번이면 우연이 아니다. 이 프로젝트의 스타일 이름은 짧은 것에
//                        접미사를 붙여 파생시키는 규칙이라(Link·Title·Row·On·Off),
//                        짧은 쪽을 앵커로 쓰면 긴 쪽이 먼저 걸린다.
//
//   부정 단언을 쓸 때    **대상 파일이 맞는지부터 확인한다.**
//                        「없다」를 보는 단언은 엉뚱한 파일을 뒤져도 통과한다 — 앵커가
//                        여럿인 것도, 패턴이 안 맞는 것도 아니고, 파일 자체가 틀린 경우다.
//                        score.check가 「타이머까지 막지는 않는다」를 ScoreboardPanel에서
//                        찾았는데 TimerPanel은 AssignmentScreen이 그린다. 변이를 넣어도
//                        늘 통과했다.
//                        긍정 단언 하나로 대상을 먼저 고정하고 그 위에서 부정을 봐라:
//                          const timer = screen.slice(screen.indexOf('<TimerPanel'), …);
//                          assert.ok(timer.length > 0, 'TimerPanel을 못 찾았다');   // 대상 고정
//                          assert.ok(!/disabled/.test(timer), '…');                 // 그 위에서 부정
//                        「그 문구가 이 파일에 있어야 할 이유가 있는가」를 먼저 물어라.
//
//                        **의도보다 넓게 잡는 것도 같은 종류다.** 대상 파일이 맞아도
//                        패턴이 막으려던 것보다 넓으면, 나중에 무해한 코드가 걸린다.
//                        memberrow가 스탯 바에 `!/Pressable|onPress/`를 걸어 두었는데
//                        막으려던 것은 「스탯 바를 눌러 멤버 탭으로 간다」였다. 값 옆에
//                        아무 데도 안 가는 ⓘ를 붙이자 그 단언이 그것을 잡았다.
//                        「누르는가」가 아니라 「어디로 보내는가」를 봐야 했다 —
//                        `!/onGoMembers|onGoTile|navigation\./`.
//                        부정 단언을 쓸 때 **막으려는 것을 한 문장으로 적어 보고, 패턴이
//                        그 문장보다 넓지 않은지** 확인해라. 넓으면 지금은 통과해도
//                        나중에 엉뚱한 것을 막고, 그때는 검사가 틀렸는지 코드가 틀렸는지
//                        판단하는 데 시간이 든다.
//
//   사본을 셀 때          **이름과 값 양쪽으로 찾는다.**
//                        지금까지의 넷은 「찾긴 찾았는데 엉뚱한 것을 봤다」였다.
//                        이건 다르다 — **찾는 대상에 이름이 없어서 검색이 안 닿는다.**
//
//                        유예 3시간을 utils로 모을 때 MATCH_GRACE_MS와
//                        NEXT_MATCH_GRACE_MS 둘만 잡혔다. TeamHomeScreen은 같은 값을
//                        `Date.now() - 3 * 60 * 60 * 1000`으로 식 안에 그대로 써서,
//                        이름으로 grep해도 안 나왔다. 「사본이 둘」로 알고 모았는데
//                        셋이었고, 그 셋째는 한 달 뒤 다른 작업 중에 우연히 걸렸다.
//
//                        인라인 상수·인라인 식·복사된 삼항식이 다 여기 해당한다.
//                        이름을 붙일 만큼 중요하다고 판단되지 않은 것일수록 흩어져 있고,
//                        흩어진 것을 셀 때 이름으로 세면 그것들만 빠진다.
//
//                          이름으로:  /const \w*GRACE\w*_MS/
//                          값으로:    /3 \* 60 \* 60 \* 1000/
//
//                        ⚠ 값으로 찾으면 **그 사실을 적은 주석의 같은 식**이 걸린다.
//                          위 세 번째 구분과 같은 함정이다 — 근거를 적으면 그 이름이나
//                          값이 주석에 남는다. 주석을 걷어낸 뒤에 센다:
//                            src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
//
//
//   존재와 동작            **「있는가」와 「그것이 하는 일이 맞는가」는 다른 단언이다.**
//                        앞의 여섯은 「어디를 보는가」의 문제였다. 이건 「무엇을
//                        묻는가」의 문제다 — 자리는 맞게 짚었는데 물음이 약하다.
//
//                        푸시 검사에 이렇게 썼다:
//
//                          ok(/catch \(err\) \{/.test(svc), 'catch가 없다')
//
//                        변이로 catch를 `catch (err) { throw err; }`로 바꿨더니
//                        그대로 통과했다. 이 단언이 지키려던 것은 「삼킨다」인데
//                        실제로 물은 것은 「catch라는 글자가 있다」였다.
//                        다시 던지는 catch는 catch가 없는 것보다 나을 게 없다.
//                        블록을 떼어 안을 봐야 한다:
//
//                          const body = /* 균형 잡힌 } 까지 잘라낸다 */;
//                          ok(!/\bthrow\b/.test(body), '다시 던진다')
//                          ok(/return \(pushStatus = 'failed'\)/.test(body), '결과를 안 남긴다')
//
//                        ⚠ 본문을 뗄 때 **첫 `{`부터 세면 안 된다.**
//                          `signOut(): Promise<{ serverRevoked: boolean }> {` 에서
//                          첫 `{`는 반환 타입의 것이라 본문이 통째로 잘린다 —
//                          실제로 걸렸고, 잘린 본문으로 세 단언이 거짓 실패를 냈다.
//                          서명 줄의 **마지막** `{`부터 센다.
//
//   하나와 전부            **「하나라도 있는가」와 「전부에 있는가」는 다른 단언이다.**
//                        위와 같은 뿌리다. 표지·규약처럼 여러 자리에 똑같이
//                        붙어야 하는 것에 존재 단언을 쓰면, 하나만 남아도 통과한다.
//
//                          약함:  ok(/console\.warn\('\[push\]/.test(svc), ...)
//                          맞음:  const warns = svc.match(/console\.warn\([^,)]*/g) ?? [];
//                                 ok(warns.length >= 3, ...)
//                                 ok(warns.every((w) => w.includes('[push]')), ...)
//
//                        변이로 세 자리 중 하나에서 표지를 떼었더니 약한 쪽은
//                        조용했다. 나머지 둘이 남아 있었기 때문이다.
//
//                        ⚠ 창(N줄·N자)으로 훑는 것도 여기 해당한다.
//                          `.catch(`를 호출 뒤 5줄 안에서 찾다가 여러 줄에 걸친
//                          호출 넷을 전부 거짓 양성으로 올렸다(`.catch`가 7줄 뒤였다).
//                          `deleteAccount`의 throw를 200자 창으로 찾다가 옆 함수의
//                          throw가 대신 걸리기도 했다. **창이 아니라 경계로 자른다** —
//                          문장 끝까지, 블록 끝까지, 함수 본문까지.
//
//                        ⚠ 이 항목을 적은 지 얼마 안 돼 **또 재현됐다.** 당겨서
//                          새로고침의 finally를 이렇게 봤다:
//
//                            /finally \{[\s\S]{0,80}setRefreshing\(false\)/
//
//                          변이로 `finally {}` 를 비우고 그 **뒤에**
//                          setRefreshing(false)를 뒀더니 80자 창 안에 들어와서
//                          통과했다. 빈 finally인데 「멈춘다」로 읽힌 것이다.
//
//                          그래서 처방을 적어 둔다. 「창으로 훑지 마라」만 있으면
//                          무엇으로 대신할지 모른다 —
//
//                          **여는 중괄호부터 괄호 균형으로 블록을 떼어낸다.**
//
//                            const block = (() => {
//                              const at = body.indexOf('finally');
//                              if (at < 0) return '';
//                              let d = 0;
//                              for (let i = body.indexOf('{', at); i < body.length; i += 1) {
//                                if (body[i] === '{') d += 1;
//                                else if (body[i] === '}') {
//                                  d -= 1;
//                                  if (d === 0) return body.slice(at, i + 1);
//                                }
//                              }
//                              return '';
//                            })();
//                            ok(block !== '', '…블록이 없다');        // 있는가
//                            ok(/setRefreshing/.test(block), '…비어 있다');  // 안에 있는가
//
//                          **둘로 나눠 단언한다.** 「블록이 없다」와 「블록은 있는데
//                          비어 있다」는 고치는 방법이 다르고, 하나로 합치면 어느
//                          쪽인지 메시지가 안 알려준다.
//
//                          ⚠ 시작 위치를 `body.indexOf('{', at)`로 잡는 것이 요점이다.
//                            `at`부터 세면 `finally` 글자 안에 { 가 없으니 첫 { 를
//                            찾아야 하는데, 반환 타입에 객체 리터럴이 있는 함수에서는
//                            그 { 가 본문이 아닐 수 있다(signout.check이 실제로 걸렸다).
//                            블록을 뗄 때는 **키워드 바로 뒤의 첫 {** 가 맞고,
//                            함수 본문을 뗄 때는 **서명 줄의 마지막 {** 가 맞다.
//
//                        이 둘은 변이 시험이 아니면 안 드러난다. 통과하는 검사는
//                        약한 검사와 구별되지 않는다. 새 검사를 쓰면 반드시
//                        「이 단언이 막으려는 것」을 한 번 주입해 보고 커밋한다.
//
//
//   부르는 자리를 셀 때    **호출과 참조를 둘 다 센다.**
//                        `foo(` 만 찾으면 참조 전달이 빠진다. 리액트에서는
//                        핸들러를 참조로 넘기는 쪽이 흔하다:
//
//                          호출:  signOut();          onPress={() => signOut()}
//                          참조:  onPress={signOut}   onPress={handleClose}
//                                 useEffect(..., [signOut])   props로 내려보내기
//
//                        로그아웃의 「부르고 버리는 프로미스」를 훑을 때 둘을
//                        찾았다고 보고했는데 넷이었다. TeamStartScreen의
//                        `onPress={signOut}`과 MySettings의 `if (ok) signOut()`이
//                        빠졌다 — 앞의 것은 참조라 호출 패턴에 안 걸렸고, 뒤의 것은
//                        줄 앞이 `)` 로 끝나 「대입·참조 뒤」로 걸러졌다.
//
//                        참조로 넘긴 자리는 **누가 언제 부를지 모르는 자리**라
//                        오히려 더 위험하다. 그 함수가 던지면 잡을 사람이 없다.
//
//                          이름으로 한 번 훑고(정의·호출·참조가 다 걸린다),
//                          그 목록에서 「이건 정의다」를 빼는 방향으로 좁힌다.
//                          호출 형태로 먼저 좁히면 좁힌 뒤에는 못 넓힌다.
//
//                        이것이 「셀 때 빠진다」 계열의 세 번째다:
//                          여섯째  인라인 상수 — 이름이 없어서 안 걸린다
//                          여덟째  창(N줄·N자) — 경계 밖이라 안 걸린다
//                          아홉째  참조 전달 — 호출 형태가 아니라서 안 걸린다
//                        셋 다 「무엇을 후보로 삼는가」에서 이미 빠진 경우다.
//                        찾는 규칙이 좁으면 검사가 아무리 정확해도 소용이 없다.
//
//
//   인자를 셀 때            **위치로 센다. 값의 모양으로 찾지 마라.**
//                        「셀 때 빠진다」 넷째다. 앞의 셋은 후보를 못 찾은 것이고
//                        이건 **찾긴 했는데 인자를 잘못 읽은** 경우다.
//
//                        notifyTeam의 다섯 번째 인자(대상)를 이렇게 찾았다:
//
//                          re.search(r',\s*(notVoted\w*|\w*UserIds)\s*,', body)
//
//                        실제 코드에는 `targets`도 있었다. 이름이 그 패턴에 안 맞아
//                        「팀 전체」로 읽혔고, 그래서 「댓글이 팀 전체로 간다」는
//                        표를 만들어 보고했다. 사실은 글쓴이 한 사람이었다.
//                        그 틀린 표를 근거로 지시가 내려왔고, 코드를 다시 읽고서야
//                        뒤집혔다.
//
//                        인자는 **위치가 의미**다. 이름은 부르는 쪽 마음이다.
//                        괄호 균형을 세어 최상위 콤마로 자른다:
//
//                          notifyTeam(  teamId, title, body, excludeUserId, userIds, kind  )
//                                        [0]    [1]    [2]      [3]          [4]     [5]
//
//                        ⚠ 자르는 코드도 조심할 것이 둘 있다.
//                          · 템플릿 문자열 안의 콤마 — `${a}, ${b}` 를 인자로 센다.
//                            백틱을 만나면 세지 않도록 토글을 둔다.
//                          · 인자 개수가 자리마다 다르다 — 우천 안내는 4개,
//                            나머지는 5개였다. 「n번째」를 고정으로 가정하면 깨진다.
//
//                        같은 이유로 **호출 자리를 고칠 때도 위치로 붙인다.**
//                        4개짜리에 여섯째를 붙이려면 다섯째 자리에 undefined를
//                        넣어야 한다. 그걸 모르고 일괄 변환을 돌리면 조용히
//                        kind가 대상 자리에 들어간다.
////
//   세기 전에            **「이것이 셀 대상인가」를 먼저 묻는다.**
//                        「셀 때 빠진다」의 **뒤집힌 모양**이다. 앞의 넷은 후보에서
//                        빠진 경우인데, 이건 **후보가 아닌 것이 들어온** 경우다.
//
//                        expo-system-ui 작업의 판정을 「밝게 뜨는 요소들이
//                        어두워지는가」로 잡았다. 고친 뒤에도 텍스트 선택 툴바는
//                        그대로 밝았고 — 실패로 보였다. 재보니 성공이었다:
//
//                          dumpsys window windows → InputMethod 창의 주인은
//                          com.google.android.inputmethod.latin (Gboard). 별개 프로세스다.
//                          AppCompatDelegate.setDefaultNightMode는 **자기 앱의 리소스
//                          해석**을 바꾸는 것이라 남의 프로세스 창에 닿지 않는다.
//
//                        「밝게 보이는 것」을 한 덩어리로 묶고 전부 우리 것이라
//                        가정했다. **창의 주인을 먼저 세지 않았다.**
//
//                        빠지는 쪽과 들어오는 쪽은 증상이 다르다:
//                          빠지면    없는 것을 없다고 한다 → 결함을 놓친다
//                          들어오면  고칠 수 없는 것을 판정에 넣는다 →
//                                    **성공이 실패로 보인다**
//                        뒤쪽이 더 나쁘게 끝날 수 있다 — 멀쩡한 고침을 되돌리게 된다.
//
//                        검사에서도 같다. 부정 단언의 대상 파일을 확인하라는 위 항목이
//                        이것의 파일 판이고, 이건 **소유자 판**이다. 세기 전에 묻는다:
//                          이 목록의 각 항목이 정말 내가 바꿀 수 있는 것인가.
//                          아니라면 그건 대조군이지 판정 대상이 아니다.
//                        (실제로 런처를 대조군으로 쓰니 판정이 바로 났다 —
//                         런처는 night 아님, 우리 앱은 night.)

// 이 구분은 세어 보고 정했다. 정규식으로 소스를 보는 단언이 157개인데 패턴이 2회 이상
// 매치되는 것이 13개였고, 그중 9개가 구조적 2회(정의부+사용부)였다. 전부에 개수를 거는
// 헬퍼를 기본값으로 두면 9개가 즉시 깨지고 각각 예외를 달아야 한다 — 부정 단언 감사기가
// 38개 중 22개를 「판정 불가」로 내놓아 폐기된 것과 같은 구조가 된다.
//
// ── 왜 공용 파일인가 ────────────────────────────────────────────────
//
// onlyIndexOf가 teamsettings.check와 invitecard.check 두 곳에 복사돼 있었다.
// score·timerring·upcoming에서 「검사가 자기 사본을 시험한다」를 셋 걷어낸 직후였다.
// 한쪽만 고치면 다른 쪽이 옛 방식으로 남는다.
import assert from 'node:assert/strict';

/**
 * indexOf인데, 두 번 이상 나오면 실패한다.
 *
 * 문자열 앵커를 쓸 일이 있으면 이걸 통과시켜라. 앵커가 1회가 아니면 실패한다는 게
 * 기본값이어야 한다.
 *
 * 그냥 indexOf는 같은 꼴이 둘이 되는 날 **조용히 앞의 것을 집는다.** 세 번 겪었다.
 *
 *   teamsettings   </> + )} 가 둘이라 저장 버튼 쪽을 집었다. 총무 구간을 통째로 지운
 *                  변이가 그 틈으로 샜다.
 *   uidetail       sectionHeadLink가 둘이 되면서 히어로 링크를 집었다.
 *   teamprofile    profileBits 첫 것이 props 인터페이스라 렌더 자리에 닿지 않았다.
 *                  무엇을 넣어도 통과하는 단언이 됐다.
 *
 * 개별로 고치는 대신 경로를 없앤다. 못 찾아도, 둘 이상이어도 「재료 없음」으로 시끄럽게
 * 끝난다 — 잘못된 통과보다 시끄러운 실패가 낫다.
 */
export const onlyIndexOf = (src: string, needle: string, what: string) => {
  const n = src.split(needle).length - 1;
  assert.equal(n, 1, `${what}: 앵커가 ${n}개다(1개여야 한다) — ${needle.slice(0, 50)}`);
  return src.indexOf(needle);
};

/**
 * 정규식판 짝 — 매치가 정확히 하나일 때만 통과한다.
 *
 * onlyIndexOf가 「앞의 것을 집는」 고장을 막듯, 이건 「어느 하나만 있어도 통과」를 막는다.
 * 증상이 같다: 의도한 자리가 사라져도 다른 자리가 검사를 통과시킨다.
 *
 * 기본값으로 쓰지 마라. 위 머리말의 구분대로 「이 자리인가」를 물을 때만 쓴다 —
 * 「이름이 쓰이는가」에 걸면 정의부+사용부 때문에 늘 2회라 헛돈다.
 *
 * 자리를 특정할 수 있으면 파서가 더 낫다. 이건 파서를 쓰기엔 과한 자리용이다.
 */
export const onlyMatch = (src: string, re: RegExp, what: string) => {
  const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
  const hits = src.match(g) ?? [];
  assert.equal(hits.length, 1, `${what}: 매치가 ${hits.length}개다(1개여야 한다) — ${re.source.slice(0, 50)}`);
  return hits[0];
};
