//                        것은 토스트나 로그가 자른 것이었다.
//
//                        직접 재는 수단이 있었다:
//
//                          supabase functions list       version · updated_at · sha256  (~10초)
//                          supabase functions download   배포된 소스를 그대로 받는다
//
//                        ⚠ **간접 근거로 단정한 것이 잘못이다.** 「문구가 다르다」는
