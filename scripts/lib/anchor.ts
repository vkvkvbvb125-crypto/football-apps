//
//                        개수는 「없어진 것을 알아채려고」 두는 것이지
//                        「무엇이 있는지」를 지키지 못한다. 상쇄를 못 본다.
//                        자리까지 봐야 하는 것이면 개수 옆에 **어디에 있는가**를 같이 걸어라.

//   잴 수 있는데 안 쟀다  **간접 근거로 단정하기 전에, 직접 재는 수단이 있는지 물어라.**
